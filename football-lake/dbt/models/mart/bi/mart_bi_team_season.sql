{# BI team-season mart. Grain: (competition_key, season, team_key).
   Upstream mart_bi_team_match is required and must pass its uniqueness/result tests.
   No joins and no arbitrary deduplication: source_row_count vs matches_total exposes bad input.
   Distinct counts do not repair duplicated metric rows; reject those groups via the test.
   Result and statistic aggregates use has_result=true; schedules remain in match counts.
   SUM of no observed values stays NULL. Observation counts include known zeros.
   Ratios use sums over paired observations, never the mean of per-match ratios.
   Build BOTH BI models in the SAME sandbox; the upstream BI Parquet is not yet published.
#}

with team_matches as (
    select
        competition_key,
        season,
        team_key,
        match_key,
        side,
        is_finished,
        has_result,
        team_result,
        points,
        goals_for,
        goals_against,
        goal_difference,
        xg_for,
        xg_against,
        xg_difference,
        goals_minus_xg,
        shots,
        shots_target,
        corners,
        fouls,
        yellows,
        reds,
        deep,
        deep_allowed,
        xpts,
        npxg,
        npxga,
        ppda_att,
        ppda_def
    from {{ ref('mart_bi_team_match') }}
),

aggregated as (
    select
        competition_key,
        season,
        team_key,
        count(*) as source_row_count,
        count(distinct match_key) filter (where true) as matches_total,
        count(distinct match_key) filter (where true and is_finished) as matches_finished,
        count(distinct match_key) filter (where true and has_result) as matches_with_result,
        count(distinct match_key) filter (where true and not has_result) as matches_without_result,
        count(distinct match_key) filter (where true and has_result and team_result = 'W') as wins,
        count(distinct match_key) filter (where true and has_result and team_result = 'D') as draws,
        count(distinct match_key) filter (where true and has_result and team_result = 'L') as losses,
        sum(points) filter (where true and has_result) as points_total,
        sum(goals_for) filter (where true and has_result) as goals_for_total,
        sum(goals_against) filter (where true and has_result) as goals_against_total,
        sum(goal_difference) filter (where true and has_result) as goal_difference_total,
        count(distinct match_key) filter (where side = 'h') as home_matches_total,
        count(distinct match_key) filter (where side = 'h' and is_finished) as home_matches_finished,
        count(distinct match_key) filter (where side = 'h' and has_result) as home_matches_with_result,
        count(distinct match_key) filter (where side = 'h' and not has_result) as home_matches_without_result,
        count(distinct match_key) filter (where side = 'h' and has_result and team_result = 'W') as home_wins,
        count(distinct match_key) filter (where side = 'h' and has_result and team_result = 'D') as home_draws,
        count(distinct match_key) filter (where side = 'h' and has_result and team_result = 'L') as home_losses,
        sum(points) filter (where side = 'h' and has_result) as home_points_total,
        sum(goals_for) filter (where side = 'h' and has_result) as home_goals_for_total,
        sum(goals_against) filter (where side = 'h' and has_result) as home_goals_against_total,
        sum(goal_difference) filter (where side = 'h' and has_result) as home_goal_difference_total,
        count(distinct match_key) filter (where side = 'a') as away_matches_total,
        count(distinct match_key) filter (where side = 'a' and is_finished) as away_matches_finished,
        count(distinct match_key) filter (where side = 'a' and has_result) as away_matches_with_result,
        count(distinct match_key) filter (where side = 'a' and not has_result) as away_matches_without_result,
        count(distinct match_key) filter (where side = 'a' and has_result and team_result = 'W') as away_wins,
        count(distinct match_key) filter (where side = 'a' and has_result and team_result = 'D') as away_draws,
        count(distinct match_key) filter (where side = 'a' and has_result and team_result = 'L') as away_losses,
        sum(points) filter (where side = 'a' and has_result) as away_points_total,
        sum(goals_for) filter (where side = 'a' and has_result) as away_goals_for_total,
        sum(goals_against) filter (where side = 'a' and has_result) as away_goals_against_total,
        sum(goal_difference) filter (where side = 'a' and has_result) as away_goal_difference_total,
        sum(xg_for) filter (where has_result) as xg_for_total,
        count(xg_for) filter (where has_result) as xg_for_observations,
        sum(xg_against) filter (where has_result) as xg_against_total,
        count(xg_against) filter (where has_result) as xg_against_observations,
        sum(xg_difference) filter (where has_result) as xg_difference_total,
        count(xg_difference) filter (where has_result) as xg_difference_observations,
        sum(goals_minus_xg) filter (where has_result) as goals_minus_xg_total,
        count(goals_minus_xg) filter (where has_result) as goals_minus_xg_observations,
        sum(shots) filter (where has_result) as shots_total,
        count(shots) filter (where has_result) as shots_observations,
        sum(shots_target) filter (where has_result) as shots_target_total,
        count(shots_target) filter (where has_result) as shots_target_observations,
        sum(corners) filter (where has_result) as corners_total,
        count(corners) filter (where has_result) as corners_observations,
        sum(fouls) filter (where has_result) as fouls_total,
        count(fouls) filter (where has_result) as fouls_observations,
        sum(yellows) filter (where has_result) as yellows_total,
        count(yellows) filter (where has_result) as yellows_observations,
        sum(reds) filter (where has_result) as reds_total,
        count(reds) filter (where has_result) as reds_observations,
        sum(deep) filter (where has_result) as deep_total,
        count(deep) filter (where has_result) as deep_observations,
        sum(deep_allowed) filter (where has_result) as deep_allowed_total,
        count(deep_allowed) filter (where has_result) as deep_allowed_observations,
        sum(xpts) filter (where has_result) as xpts_total,
        count(xpts) filter (where has_result) as xpts_observations,
        sum(npxg) filter (where has_result) as npxg_total,
        count(npxg) filter (where has_result) as npxg_observations,
        sum(npxga) filter (where has_result) as npxga_total,
        count(npxga) filter (where has_result) as npxga_observations,
        sum(shots_target) filter (where has_result and shots_target is not null and shots is not null) as shot_accuracy_numerator_total,
        sum(shots) filter (where has_result and shots_target is not null and shots is not null) as shot_accuracy_denominator_total,
        count(*) filter (where has_result and shots_target is not null and shots is not null) as shot_accuracy_observations,
        sum(ppda_att) filter (where has_result and ppda_att is not null and ppda_def is not null) as ppda_numerator_total,
        sum(ppda_def) filter (where has_result and ppda_att is not null and ppda_def is not null) as ppda_denominator_total,
        count(*) filter (where has_result and ppda_att is not null and ppda_def is not null) as ppda_observations
    from team_matches
    group by competition_key, season, team_key
)

select
    a.competition_key,
    a.season,
    a.team_key,
    a.source_row_count,
    a.matches_total,
    a.matches_finished,
    a.matches_with_result,
    a.matches_without_result,
    a.wins,
    a.draws,
    a.losses,
    a.points_total,
    1.0 * a.points_total / nullif(a.matches_with_result, 0) as points_per_match,
    1.0 * a.wins / nullif(a.matches_with_result, 0) as win_rate,
    a.goals_for_total,
    a.goals_against_total,
    a.goal_difference_total,
    a.home_matches_total,
    a.home_matches_finished,
    a.home_matches_with_result,
    a.home_matches_without_result,
    a.home_wins,
    a.home_draws,
    a.home_losses,
    a.home_points_total,
    1.0 * a.home_points_total / nullif(a.home_matches_with_result, 0) as home_points_per_match,
    1.0 * a.home_wins / nullif(a.home_matches_with_result, 0) as home_win_rate,
    a.home_goals_for_total,
    a.home_goals_against_total,
    a.home_goal_difference_total,
    a.away_matches_total,
    a.away_matches_finished,
    a.away_matches_with_result,
    a.away_matches_without_result,
    a.away_wins,
    a.away_draws,
    a.away_losses,
    a.away_points_total,
    1.0 * a.away_points_total / nullif(a.away_matches_with_result, 0) as away_points_per_match,
    1.0 * a.away_wins / nullif(a.away_matches_with_result, 0) as away_win_rate,
    a.away_goals_for_total,
    a.away_goals_against_total,
    a.away_goal_difference_total,
    a.xg_for_total,
    a.xg_for_observations,
    a.xg_against_total,
    a.xg_against_observations,
    a.xg_difference_total,
    a.xg_difference_observations,
    a.goals_minus_xg_total,
    a.goals_minus_xg_observations,
    a.shots_total,
    a.shots_observations,
    a.shots_target_total,
    a.shots_target_observations,
    a.corners_total,
    a.corners_observations,
    a.fouls_total,
    a.fouls_observations,
    a.yellows_total,
    a.yellows_observations,
    a.reds_total,
    a.reds_observations,
    a.deep_total,
    a.deep_observations,
    a.deep_allowed_total,
    a.deep_allowed_observations,
    a.xpts_total,
    a.xpts_observations,
    a.npxg_total,
    a.npxg_observations,
    a.npxga_total,
    a.npxga_observations,
    1.0 * a.xg_for_total / nullif(a.xg_for_observations, 0) as xg_for_per_match,
    1.0 * a.xg_against_total / nullif(a.xg_against_observations, 0) as xg_against_per_match,
    1.0 * a.shots_total / nullif(a.shots_observations, 0) as shots_per_match,
    1.0 * a.shots_target_total / nullif(a.shots_target_observations, 0) as shots_target_per_match,
    a.shot_accuracy_numerator_total,
    a.shot_accuracy_denominator_total,
    a.shot_accuracy_observations,
    1.0 * a.shot_accuracy_numerator_total / nullif(a.shot_accuracy_denominator_total, 0) as shot_accuracy,
    a.ppda_numerator_total,
    a.ppda_denominator_total,
    a.ppda_observations,
    1.0 * a.ppda_numerator_total / nullif(a.ppda_denominator_total, 0) as ppda
from aggregated a
