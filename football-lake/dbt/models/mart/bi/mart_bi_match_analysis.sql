{{ config(materialized='external') }}
{# One row per match_key, retaining every fact_match row without joins or deduplication.
   Actual match statistics are post-match data, not pre-match prediction features.
   All differences are home minus away. Missing values remain NULL, including partial scores.
   Preserve source anomalies and core_result; tests expose conflicts rather than repairing them.
#}

with source as (
    select
        m.*,
        (m.is_finished and m.home_goals is not null and m.away_goals is not null) as has_result,
        (m.is_finished and (m.home_goals is null or m.away_goals is null)) as is_missing_final_score
    from {{ ref('fact_match') }} m
),

base as (
    select
        s.match_key,
        s.competition_key,
        s.season,
        s.home_key,
        s.away_key,
        s.match_date,
        s.kickoff_utc,
        s.status,
        s.stage,
        s.matchday,
        s.af_round,
        s.referee,
        s.venue_name,
        s.is_finished,
        s.has_result,
        s.is_missing_final_score,
        s.result as core_result,
        case when s.has_result then s.home_goals end as home_goals,
        case when s.has_result then s.away_goals end as away_goals,
        case when s.has_result then s.result end as result,
        case when s.is_finished then s.ht_home_goals end as ht_home_goals,
        case when s.is_finished then s.ht_away_goals end as ht_away_goals,
        case when s.is_finished then s.home_xg end as home_xg,
        case when s.is_finished then s.away_xg end as away_xg,
        case when s.is_finished then s.home_shots end as home_shots,
        case when s.is_finished then s.away_shots end as away_shots,
        case when s.is_finished then s.home_shots_target end as home_shots_target,
        case when s.is_finished then s.away_shots_target end as away_shots_target,
        case when s.is_finished then s.home_corners end as home_corners,
        case when s.is_finished then s.away_corners end as away_corners,
        case when s.is_finished then s.home_fouls end as home_fouls,
        case when s.is_finished then s.away_fouls end as away_fouls,
        case when s.is_finished then s.home_yellows end as home_yellows,
        case when s.is_finished then s.away_yellows end as away_yellows,
        case when s.is_finished then s.home_reds end as home_reds,
        case when s.is_finished then s.away_reds end as away_reds,
        case when s.is_finished then s.weather_temp_c end as weather_temp_c,
        case when s.is_finished then s.weather_precip_mm end as weather_precip_mm,
        case when s.is_finished then s.weather_wind_kmh end as weather_wind_kmh,
        case when s.is_finished then s.weather_humidity_pct end as weather_humidity_pct,
        case when s.is_finished then s.weather_code end as weather_code,
        s.fdo_match_id,
        s.understat_match_id,
        s.af_fixture_id,
        s.openliga_match_id,
        s.goals_conflict,
        s.in_fdo,
        s.in_couk,
        s.in_understat,
        s.in_api_football,
        s.in_openliga,
        s.in_odds_api,
        s.has_weather
    from source s
)

select
    b.match_key,
    b.competition_key,
    b.season,
    b.home_key,
    b.away_key,
    b.match_date,
    b.kickoff_utc,
    b.status,
    b.stage,
    b.matchday,
    b.af_round,
    b.referee,
    b.venue_name,
    b.is_finished,
    b.has_result,
    b.is_missing_final_score,
    b.core_result,
    b.home_goals,
    b.away_goals,
    b.result,
    case when b.has_result then
        case when b.home_goals > b.away_goals then 3
             when b.home_goals = b.away_goals then 1 else 0 end
    end as home_points,
    case when b.has_result then
        case when b.away_goals > b.home_goals then 3
             when b.away_goals = b.home_goals then 1 else 0 end
    end as away_points,
    case when b.has_result then (b.home_goals > b.away_goals)::integer end as is_home_win,
    case when b.has_result then (b.home_goals = b.away_goals)::integer end as is_draw,
    case when b.has_result then (b.home_goals < b.away_goals)::integer end as is_away_win,
    b.home_goals + b.away_goals as total_goals,
    b.home_goals - b.away_goals as goal_difference,
    b.ht_home_goals,
    b.ht_away_goals,
    b.home_xg,
    b.away_xg,
    b.home_xg + b.away_xg as total_xg,
    b.home_xg - b.away_xg as xg_difference,
    b.home_shots,
    b.away_shots,
    b.home_shots + b.away_shots as total_shots,
    b.home_shots - b.away_shots as shots_difference,
    b.home_shots_target,
    b.away_shots_target,
    b.home_shots_target + b.away_shots_target as total_shots_target,
    b.home_shots_target - b.away_shots_target as shots_target_difference,
    b.home_corners,
    b.away_corners,
    b.home_corners + b.away_corners as total_corners,
    b.home_corners - b.away_corners as corners_difference,
    b.home_fouls,
    b.away_fouls,
    b.home_fouls + b.away_fouls as total_fouls,
    b.home_fouls - b.away_fouls as fouls_difference,
    b.home_yellows,
    b.away_yellows,
    b.home_yellows + b.away_yellows as total_yellows,
    b.home_yellows - b.away_yellows as yellows_difference,
    b.home_reds,
    b.away_reds,
    b.home_reds + b.away_reds as total_reds,
    b.home_reds - b.away_reds as reds_difference,
    case when b.has_result then b.home_goals - b.home_xg end as home_goals_minus_xg,
    1.0 * b.home_shots_target / nullif(b.home_shots, 0) as home_shot_accuracy,
    case when b.has_result then b.away_goals - b.away_xg end as away_goals_minus_xg,
    1.0 * b.away_shots_target / nullif(b.away_shots, 0) as away_shot_accuracy,
    (b.home_xg is not null and b.away_xg is not null) as has_xg_pair,
    (b.home_shots is not null and b.away_shots is not null) as has_shots_pair,
    (b.home_shots_target is not null and b.away_shots_target is not null) as has_shots_target_pair,
    (b.home_corners is not null and b.away_corners is not null) as has_corners_pair,
    (b.home_fouls is not null and b.away_fouls is not null) as has_fouls_pair,
    (b.home_yellows is not null and b.away_yellows is not null) as has_yellows_pair,
    (b.home_reds is not null and b.away_reds is not null) as has_reds_pair,
    case when b.home_shots is not null and b.home_shots_target is not null then
        (b.home_shots >= 0 and b.home_shots_target >= 0
         and b.home_shots_target <= b.home_shots)
    end as home_shots_pair_valid,
    case when b.away_shots is not null and b.away_shots_target is not null then
        (b.away_shots >= 0 and b.away_shots_target >= 0
         and b.away_shots_target <= b.away_shots)
    end as away_shots_pair_valid,
    date_part('year', b.match_date)::integer as match_year,
    date_part('month', b.match_date)::integer as match_month,
    date_part('isodow', b.match_date)::integer as match_day_of_week,
    (date_part('isodow', b.match_date) in (6, 7)) as is_weekend,
    date_part('hour', b.kickoff_utc)::integer as kickoff_hour_utc,
    b.weather_temp_c,
    b.weather_precip_mm,
    b.weather_wind_kmh,
    b.weather_humidity_pct,
    b.weather_code,
    b.fdo_match_id,
    b.understat_match_id,
    b.af_fixture_id,
    b.openliga_match_id,
    b.goals_conflict,
    b.in_fdo,
    b.in_couk,
    b.in_understat,
    b.in_api_football,
    b.in_openliga,
    b.in_odds_api,
    b.has_weather
from base b
